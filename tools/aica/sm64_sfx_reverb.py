#!/usr/bin/env python3
"""Each sound's script reverb, for src/pc/audio/sm64_aicaflow.c.

    tools/aica/sm64_sfx_reverb.py sound/sequences/00_sound_player.s > build/.../sm64_sfx_reverb.h

A sound script that wants reverb does `chan_setval N` then `chan_call .set_reverb`: N goes to the
channel's IO slot 5, which get_sound_reverb (src/audio/external.c) adds to the area's echo level
and a distance term. Every sound starts with slot 5 at 0 (the main loops clear it). AICAflow runs
no sound scripts, so the values are read here: bank b's sound i is entry i of the dynamic table
of the channel started as b (banks 8 and 9 share 3's and 5's), and its N is the first
set_reverb call on the script's straight-line path from that entry to its chan_end.
"""
import re
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    lines = [l.split("/*")[0].strip() for l in Path(sys.argv[1]).read_text().splitlines()]
    labels = {l[:-1]: i for i, l in enumerate(lines) if l.endswith(":")}
    bank_channel = {}
    for l in lines:
        m = re.fullmatch(r"seq_startchannel (\d+), (\.\w+)", l)
        if m:
            bank_channel[int(m.group(1))] = m.group(2)

    def table_of(channel):
        for l in lines[labels[channel] + 1:]:
            m = re.fullmatch(r"chan_setdyntable (\.\w+)", l)
            if m:
                return m.group(1)
            if l.startswith("chan_jump") or l == "chan_end":
                break
        return None

    def script_reverb(label):
        at, value, seen = labels[label] + 1, None, set()
        while at < len(lines) and at not in seen:
            seen.add(at)
            l = lines[at]
            m = re.fullmatch(r"chan_setval (\d+)", l)
            if m:
                value = int(m.group(1))
            elif l == "chan_call .set_reverb":
                return value or 0
            elif l == "chan_end":
                return 0
            else:
                m = re.fullmatch(r"chan_jump (\.\w+)", l)
                if m:
                    at = labels[m.group(1)] + 1
                    continue
            at += 1
        return 0

    rows = []
    for bank in sorted(bank_channel):
        table = table_of(bank_channel[bank])
        if table is None:
            continue
        index = 0
        skipping = False
        for l in lines[labels[table] + 1:]:
            if l.startswith((".ifdef", ".ifndef", ".else", ".endif")):   # the US table
                skipping = l in (".ifdef VERSION_JP", ".ifdef VERSION_EU") or (l == ".else" and not skipping)
                continue
            if skipping:
                continue
            m = re.fullmatch(r"sound_ref (\.\w+)", l)
            if not m:
                if l:
                    break
                continue
            reverb = script_reverb(m.group(1))
            if reverb:
                rows.append((bank << 28 | index << 16, reverb, m.group(1)))
            index += 1
    print("/* Generated by tools/aica/sm64_sfx_reverb.py from sound/sequences/00_sound_player.s:")
    print("   the IO slot 5 reverb each sound's script sets, by soundBits & 0xF0FF0000. */")
    print("static const struct { u32 key; u8 reverb; } sSfxScriptReverb[] = {")
    for key, reverb, label in rows:
        print(f"    {{ 0x{key:08X}u, {reverb} }},   /* {label[1:]} */")
    print("};")


if __name__ == "__main__":
    main()
